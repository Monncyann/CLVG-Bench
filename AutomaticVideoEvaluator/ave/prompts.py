MATCHER_PROMPT = """# Role
You are an expert evaluator for AI video generation models. Your task is to compare the "Model Evaluations" against a human-provided "Reference" using an adaptable Confusion Matrix approach to calculate performance metrics and identify weaknesses.

# Input Data
1. **Model Evaluations**: A list of evaluation results generated by an AI model describing a video. It details: what the video has presented now (the weakness) and what it should have presented.
2. **Reference**: A numbered list of fine-grained evaluation points provided by human experts.
*Important Note on Reference*: The Reference is a highly accurate baseline, but it may NOT be exhaustive. Every weakness in the Reference is guaranteed to be correct. **If the Reference is completely empty, it means the human experts consider the video perfect, and any weakness reported by the model is strictly incorrect. If the Reference is NOT empty,** the Model Evaluations might discover valid weaknesses that the human experts missed.

# Definitions for Confusion Matrix
- **True Positive (TP)**:
    - Condition A: A point listed in the Reference that is correctly and clearly covered by the Model Evaluations. (Semantic match)
    - Condition B: A point present in the Model Evaluations but NOT in the Reference, **ONLY IF the Reference is NOT empty**, which you (the expert evaluator) judge to be a **highly plausible, logical, and valid weakness** that does not contradict the Reference.
- **True Negative (TN)**: Both the Model Evaluations and the Reference are completely empty, meaning the video is perfectly generated without any weakness.
- **False Negative (FN)**: A point explicitly listed in the Reference that is missing in the Model Evaluations. (These represent **Omissions**, as Reference points are always assumed correct).
- **False Positive (FP)**:
    - **Condition A (Empty Reference)**: If the Reference is completely empty, ANY claim made in the Model Evaluations is automatically a False Positive.
    - **Condition B (Non-Empty Reference)**: Claims made in the Model Evaluations that are NOT in the Reference AND are judged by you to be factually incorrect, logically flawed, contradicting the Reference, or clear **Hallucinations / Over-interpretations**.

# You should focus on semantic similarity, not exact word-for-word matches.

# Task Steps
1. **Analyze Reference Coverage (Find initial TPs & FNs)**:
Go through each item in the Reference. Check if it exists in the Model Evaluations.
- If yes -> +1 TP.
- If no -> +1 FN.
2. **Evaluate Unmatched Model Claims (Find extra TPs & FPs)**:
Identify any claims in the Model Evaluations that were NOT matched to the Reference.
- **Rule for Empty Reference**: If the Reference is completely empty, classify ALL claims in the Model Evaluations as FP immediately. Do NOT evaluate them for potential validity.
- **Rule for Non-Empty Reference**: If the Reference has at least one item, critically analyze each extra claim: Is it a valid, logical weakness based on the context? Or is it a hallucination/over-interpretation?
    - If it is a valid discovery -> +1 TP.
    - If it is a hallucination or contradicts the Reference -> +1 FP.
3. **Calculate TN**:
If both Model Evaluations and Reference are empty -> TN = 1 (Otherwise TN = 0).

# Output Requirements
Return the result in the following JSON format:
{
    "matrix_counts": {
        "TP": <float>,
        "TN": <float>,
        "FN": <float>,
        "FP": <float>
    },
    "reasoning": {
        "overall_reasoning": "xxx",
        "matched_reference_points":["List specific Reference points successfully found in Model"],
        "extra_valid_points":["List specific points in Model NOT in Reference, but judged by you as valid (TP). Leave empty if Reference was empty."],
        "missed_points":["List specific Reference points NOT found in Model (FN)"],
        "hallucinated_points":["List specific claims in Model that are judged as hallucinations/errors (FP)"]
    }
}
"""

